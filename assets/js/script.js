    /* ---------- scroll reveal ---------- */
    function initReveal() {
      window.__revealInit = true;
      if (!document.documentElement.classList.contains('reveal-ready')) return; // reduced motion / no IO / failsafe fired

      const STAGGER = 90;
      const MAX_STAGGER = 6;
      const proxyOf = new Map(); // observed element -> element to reveal
      const target = (entry) => proxyOf.get(entry.target) || entry.target;

      function done(el) {
        el.classList.add('is-in');
        // once the entrance has played, hand the element back to its normal styles (hover lifts etc.)
        const extra = parseInt(el.dataset.revealDelay || '0', 10) + (parseFloat(el.style.getPropertyValue('--rd')) || 0) * 1000;
        setTimeout(() => {
          el.removeAttribute('data-reveal');
          el.style.removeProperty('--rd');
          el.style.removeProperty('transition');
        }, 1300 + extra);
      }

      const io = new IntersectionObserver((entries) => {
        const batch = entries.filter((e) => {
          if (e.isIntersecting) return true;
          // already scrolled past (e.g. page opened on #enquire): show without animating
          if (e.boundingClientRect.bottom < 0) {
            const el = target(e);
            el.style.transition = 'none';
            done(el);
            io.unobserve(e.target);
            pending.delete(e.target);
          }
          return false;
        });
        batch.sort((a, b) =>
          (a.boundingClientRect.top - b.boundingClientRect.top) || (a.boundingClientRect.left - b.boundingClientRect.left));
        batch.forEach((e, i) => {
          const el = target(e);
          const own = parseInt(el.dataset.revealDelay || '0', 10);
          el.style.setProperty('--rd', `${(Math.min(i, MAX_STAGGER) * STAGGER + own) / 1000}s`);
          done(el);
          io.unobserve(e.target);
          pending.delete(e.target);
        });
      }, { rootMargin: '0px 0px -8% 0px', threshold: 0.12 });

      const pending = new Set(); // observed elements not yet revealed

      reveal = {
        scan(scope = document) {
          scope.querySelectorAll('[data-reveal]:not(.is-in)').forEach((el) => {
            let watch = el;
            if (el.dataset.reveal === 'clip' && el.parentElement) {
              // observe a stand-in at the same spot, since the clipped element itself reports 0% visible
              watch = document.createElement('span');
              watch.className = 'reveal-probe';
              watch.setAttribute('aria-hidden', 'true');
              el.parentElement.insertBefore(watch, el);
              const probe = watch;
              const sync = () => {
                probe.style.top = `${el.offsetTop}px`;
                probe.style.left = `${el.offsetLeft}px`;
                probe.style.width = `${el.offsetWidth}px`;
                probe.style.height = `${el.offsetHeight}px`;
              };
              sync();
              window.addEventListener('load', sync); // fonts/images can shift layout after first paint
              window.addEventListener('resize', sync);
              proxyOf.set(watch, el);
            }
            io.observe(watch);
            pending.add(watch);
          });
        }
      };
      reveal.scan(document);

      // The -8% bottom margin means the last lines of the page (footer) can never "enter".
      // When the page is scrolled to the bottom, reveal whatever is still waiting on screen.
      const flushAtBottom = () => {
        if (!pending.size) return;
        if (window.scrollY + window.innerHeight < document.documentElement.scrollHeight - 2) return;
        let i = 0;
        pending.forEach((watch) => {
          const el = proxyOf.get(watch) || watch;
          if (watch.getBoundingClientRect().top >= window.innerHeight) return;
          el.style.setProperty('--rd', `${(Math.min(i++, MAX_STAGGER) * STAGGER) / 1000}s`);
          done(el);
          io.unobserve(watch);
          pending.delete(watch);
        });
      };
      window.addEventListener('scroll', flushAtBottom, { passive: true });
      window.addEventListener('resize', flushAtBottom);
      flushAtBottom();

      // gentle parallax on the certificate background
      const cert = document.querySelector('.cert');
      if (cert) {
        let ticking = false;
        const move = () => {
          ticking = false;
          const r = cert.getBoundingClientRect();
          const vh = window.innerHeight;
          if (r.bottom < 0 || r.top > vh) return;
          const p = (vh - r.top) / (vh + r.height); // 0 → 1 while it crosses the viewport
          cert.style.setProperty('--cert-y', `${(15 + p * 70).toFixed(1)}%`);
        };
        window.addEventListener('scroll', () => {
          if (!ticking) { ticking = true; requestAnimationFrame(move); }
        }, { passive: true });
        move();
      }
    }

    /* ---------- certificate: 3D tilt that follows the pointer (desktop only) ---------- */
    function initCertTilt() {
      const section = document.querySelector('.cert');
      const tilt = section && section.querySelector('.cert-tilt');
      if (!tilt) return;
      const fine = window.matchMedia('(hover: hover) and (pointer: fine)').matches;
      if (!fine || prefersReducedMotion()) return;

      let raf = 0;
      section.addEventListener('pointermove', (e) => {
        cancelAnimationFrame(raf);
        raf = requestAnimationFrame(() => {
          const r = tilt.getBoundingClientRect();
          const dx = Math.max(-1, Math.min(1, (e.clientX - (r.left + r.width / 2)) / (r.width / 1.2)));
          const dy = Math.max(-1, Math.min(1, (e.clientY - (r.top + r.height / 2)) / (r.height / 1.2)));
          tilt.style.setProperty('--ry', `${(dx * 10).toFixed(2)}deg`);
          tilt.style.setProperty('--rx', `${(-dy * 8).toFixed(2)}deg`);
          tilt.style.setProperty('--gx', `${(50 + dx * 40).toFixed(1)}%`);
          tilt.classList.add('is-tilting');
        });
      });
      section.addEventListener('pointerleave', () => {
        cancelAnimationFrame(raf);
        ['--rx', '--ry', '--gx'].forEach((p) => tilt.style.removeProperty(p));
        tilt.classList.remove('is-tilting');
      });
    }

