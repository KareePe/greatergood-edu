    /* ---------- floating dock: CTA + back to top ---------- */
    function initFab() {
      const dock = document.getElementById('fab-dock');
      if (!dock) return;
      const hero = document.querySelector('.hero');
      const enquire = document.getElementById('enquire');
      const cta = dock.querySelector('.fab-cta');
      const topBtn = document.getElementById('fab-top');
      const bar = dock.querySelector('.fab-ring-bar');
      const CIRC = 2 * Math.PI * 21;
      const reduced = prefersReducedMotion();
      let lastY = window.scrollY;
      let compactTimer = null;
      let ticking = false;

      bar.style.strokeDasharray = CIRC;
      bar.style.strokeDashoffset = CIRC;

      function update() {
        ticking = false;
        const y = window.scrollY;
        const pastHero = hero ? hero.getBoundingClientRect().bottom <= 0 : y > 480;
        dock.classList.toggle('is-visible', pastHero);

        // scroll-progress ring
        const max = document.documentElement.scrollHeight - window.innerHeight;
        const pct = max > 0 ? Math.min(1, y / max) : 0;
        bar.style.strokeDashoffset = CIRC * (1 - pct);

        // CTA shrinks to an icon while scrolling down, springs back open when you pause or scroll up
        if (pastHero && y > lastY + 4) {
          cta.classList.add('is-compact');
          clearTimeout(compactTimer);
          compactTimer = setTimeout(() => cta.classList.remove('is-compact'), 700);
        } else if (y < lastY - 4) {
          clearTimeout(compactTimer);
          cta.classList.remove('is-compact');
        }
        lastY = y;
      }
      window.addEventListener('scroll', () => {
        if (!ticking) { ticking = true; requestAnimationFrame(update); }
      }, { passive: true });
      window.addEventListener('resize', update);
      update();

      // the form already has its own button, so tuck the floating CTA away while the form is on screen
      if ('IntersectionObserver' in window && enquire) {
        new IntersectionObserver((entries) => {
          dock.classList.toggle('cta-off', entries[0].isIntersecting);
        }, { threshold: 0.15 }).observe(enquire);
      }

      // click ripple on the CTA
      cta.addEventListener('pointerdown', (e) => {
        if (reduced) return;
        const r = cta.getBoundingClientRect();
        const dot = document.createElement('span');
        dot.className = 'fab-ripple';
        dot.style.left = `${e.clientX - r.left}px`;
        dot.style.top = `${e.clientY - r.top}px`;
        cta.appendChild(dot);
        dot.addEventListener('animationend', () => dot.remove());
      });

      // back to top: arrow "launches", page scrolls up, focus returns to the top of the page
      topBtn.addEventListener('click', () => {
        topBtn.classList.remove('is-launching');
        void topBtn.offsetWidth; // restart the animation
        topBtn.classList.add('is-launching');
        window.scrollTo({ top: 0, behavior: reduced ? 'auto' : 'smooth' });
        const brand = document.querySelector('.brand');
        if (brand) brand.focus({ preventScroll: true });
      });
      topBtn.addEventListener('animationend', () => topBtn.classList.remove('is-launching'));
    }

