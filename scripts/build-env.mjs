#!/usr/bin/env node
/**
 * Builds assets/js/env.js from .env so the browser form knows where to send leads.
 *
 *   node scripts/build-env.mjs
 *
 * Runs automatically before every `firebase deploy` (firebase.json → hosting.predeploy).
 * Run it by hand after editing .env when testing on XAMPP.
 *
 * Only keys in PUBLIC_KEYS are written: anything the browser receives is visible to every
 * visitor, so server-only values (NOTIFY_EMAIL, future secrets) must never be listed here.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const envFile = join(root, '.env');
const outFile = join(root, 'assets', 'js', 'env.js');

// .env key → name the browser sees, plus a check the value must pass
const PUBLIC_KEYS = {
  GOOGLE_SHEET_WEBHOOK: {
    as: 'googleSheetWebAppUrl',
    valid: (v) => v === '' || /^https:\/\/script\.google\.com\/macros\/s\/[\w-]+\/exec$/.test(v),
    hint: 'must be an Apps Script web app URL ending in /exec'
  }
};

function parseEnv(text) {
  const out = {};
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const m = line.match(/^(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/);
    if (!m) continue;
    let value = m[2].trim();
    if (/^(['"]).*\1$/.test(value)) value = value.slice(1, -1);
    else value = value.replace(/\s+#.*$/, ''); // inline comment after an unquoted value
    out[m[1]] = value;
  }
  return out;
}

if (!existsSync(envFile)) {
  console.warn('build-env: no .env found — copy .env.example to .env. Writing an empty env.js (form falls back to submit.php).');
}
const env = existsSync(envFile) ? parseEnv(readFileSync(envFile, 'utf8')) : {};

const publicEnv = {};
let failed = false;
for (const [key, rule] of Object.entries(PUBLIC_KEYS)) {
  const value = (process.env[key] ?? env[key] ?? '').trim(); // a real environment variable wins
  if (!rule.valid(value)) {
    console.error(`build-env: ${key} ${rule.hint} (got "${value}")`);
    failed = true;
    continue;
  }
  publicEnv[rule.as] = value;
}
if (failed) process.exit(1); // stops `firebase deploy` instead of publishing a broken form

const js = `/* Generated by scripts/build-env.mjs from .env — do not edit; edit .env and re-run. */
window.__ENV__ = Object.freeze(${JSON.stringify(publicEnv, null, 2)});
`;
writeFileSync(outFile, js);
console.log(`build-env: wrote assets/js/env.js (${Object.entries(publicEnv).map(([k, v]) => `${k}=${v ? 'set' : 'empty'}`).join(', ')})`);
